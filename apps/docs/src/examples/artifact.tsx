import { Artifact, CodeBlock, Markdown } from "kestro-ui";
import { Code, Eye, MapPin } from "lucide-react";

const itinerary = `# Kyoto in 3 days

**Travelers:** 2 adults · **Dates:** Apr 4 – Apr 7 · **Budget:** ¥180,000

## Day 1 — Higashiyama
- 08:00 Fushimi Inari before the crowds
- 12:30 Lunch at *Nishiki Market*
- 16:00 Kiyomizu-dera at golden hour

## Day 2 — Arashiyama
- Bamboo grove walk and Tenryū-ji gardens
- Sagano scenic railway (seats reserved, car 5)

## Day 3 — Slow morning
1. Tea ceremony in Gion (10:00, confirmed)
2. Shinkansen to Tokyo at 15:12

> Tip: pick up an ICOCA card at Kyoto Station on arrival.
`;

export default function Example() {
  const download = () => {
    const url = URL.createObjectURL(new Blob([itinerary], { type: "text/markdown" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = "kyoto-itinerary.md";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <Artifact
      className="h-[460px] max-w-xl"
      icon={<MapPin />}
      title="Kyoto itinerary"
      subtitle="Generated by Atlas · 3 days, 9 stops"
      copyText={itinerary}
      onDownload={download}
      tabs={[
        {
          id: "preview",
          label: "Preview",
          icon: <Eye />,
          content: <Markdown className="px-5 py-4">{itinerary}</Markdown>,
        },
        {
          id: "source",
          label: "Source",
          icon: <Code />,
          content: <CodeBlock code={itinerary} language="markdown" filename="kyoto-itinerary.md" className="m-4" />,
        },
      ]}
      footer="Last updated 2 minutes ago · v3"
    />
  );
}
